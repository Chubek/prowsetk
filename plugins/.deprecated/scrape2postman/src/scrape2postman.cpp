std::string render_postman_json(const std::vector<ResolvedEndpoint>& resolved,
                               const Scrape2PostmanOptions& options, const Redactor& redactor) {
    std::ostringstream out;
    out.imbue(std::locale::classic());
    std::string collection_description =
        "Generated by ProwseTk scrape2postman. Heuristic API discoveries; "
        "not authoritative documentation. Request bodies and credentials are omitted.";
    if (options.assistant_browser_enabled) {
        collection_description += " Assistant browser handoff is enabled via ";
        collection_description += options.assistant_browser_method.empty()
            ? "webdriver" : options.assistant_browser_method;
        collection_description += "; any user-assisted coverage remains heuristic.";
    }
    out << "{\n  \"info\": {\"name\": " << quote(options.collection_name)
        << ", \"schema\": \"https://schema.getpostman.com/json/collection/v2.1.0/collection.json\","
        << " \"description\": " << quote(collection_description) << "},\n  \"item\": [";

    // Preserve distinct hosts and methods; deduplicate exact requests only.
    std::map<std::pair<std::string, std::string>, const ResolvedEndpoint*> ordered;
    for (const auto& r : resolved)
        ordered.try_emplace(std::make_pair(r.endpoint.url, method_name(r.endpoint.method)), &r);
    bool first = true;
    for (const auto& [key, record] : ordered) {
        const auto& ep = record->endpoint;
        const auto url = safe_url(request_url(ep), options.redact_secrets, redactor);
        const auto& method = key.second;
        if (!first) out << ',';
        first = false;
        std::ostringstream description;
        description.imbue(std::locale::classic());
        description << "Heuristic discovery; inferred request. Confidence: "
                    << (std::isfinite(ep.confidence) ? std::clamp(ep.confidence, 0.0, 1.0) : 0.0);
        if (options.include_provenance) {
            description << "\nSource: " << safe_url(ep.source, options.redact_secrets, redactor)
                        << "\nDiscovery method: " << ep.discovery_method;
            if (!record->final_url.empty())
                description << "\nFinal URL: " << safe_url(record->final_url, options.redact_secrets, redactor);
            for (const auto& hop : record->redirect_chain)
                description << "\nRedirect: " << safe_url(hop, options.redact_secrets, redactor);
            for (const auto& link : record->json_discovered)
                description << "\nJSON link: " << safe_url(link, options.redact_secrets, redactor);
            if (record->status != 0) description << "\nObserved HTTP status: " << record->status;
            // Exception messages and free-text notes can contain arbitrary secrets.
            if (!record->error.empty()) description << "\nResolution failed.";
        }
        out << "\n    {\"name\": " << quote(method + " " + url)
            << ", \"request\": {\"method\": " << quote(method)
            << ", \"url\": " << quote(url)
            << ", \"description\": " << quote(description.str()) << ", \"header\": [";
        if (!ep.request_content_type.empty())
            out << "{\"key\": \"Content-Type\", \"value\": " << quote(ep.request_content_type) << '}';
        out << ']';
        // Form field names are known, but private values were never captured.
        if (ep.request_content_type == "application/x-www-form-urlencoded") {
            out << ", \"body\": {\"mode\": \"urlencoded\", \"urlencoded\": [";
            bool first_field = true;
            for (const auto& param : ep.parameters) {
                if (!first_field) out << ',';
                first_field = false;
                out << "{\"key\": " << quote(param)
                    << ", \"value\": \"\", \"description\": \"Inferred field; supply a value\"}";
            }
            out << "]}";
        }
        out << "}, \"response\": []}";
    }
    out << "\n  ]\n}\n";
    return out.str();
}

void Scrape2PostmanResult::write_postman_json(const std::filesystem::path& path) const {
    std::ofstream file;
    file.exceptions(std::ios::failbit | std::ios::badbit);
    file.open(path, std::ios::binary | std::ios::trunc);
    file << postman_json;
    file.close();
}

Scrape2PostmanResult scrape_from_document(const Document& document,
    const Scrape2PostmanOptions& options, const Redactor& redactor) {
    return convert(scrape2oapi::scrape_from_document(document, options, redactor), options, redactor);
}

Scrape2PostmanResult scrape_from_session(Session& session, const Scrape2PostmanOptions& options) {
    return convert(scrape2oapi::scrape_from_session(session, options), options, Redactor());
}

Scrape2PostmanResult scrape(Session& session, const Scrape2PostmanOptions& options) {
    // Propagate navigation failure instead of exporting a stale page.
    if (!options.html.empty()) {
        auto base = options.base_url.empty() ? options.url : options.base_url;
        session.load_html(options.html, base.empty() ? "https://example.com/" : base);
    } else if (!options.url.empty()) session.navigate(options.url);
    return scrape_from_session(session, options);
}
