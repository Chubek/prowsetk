std::string quote(std::string_view value) {
    constexpr char hex[] = "0123456789abcdef";
    std::string out = "\"";
    for (unsigned char c : value) {
        if (c == '"' || c == '\\') { out += '\\'; out += static_cast<char>(c); }
        else if (c < 0x20) {
            out += "\\u00"; out += hex[c >> 4]; out += hex[c & 15];
        } else out += static_cast<char>(c);
    }
    return out + '"';
}

std::string decode_key(std::string_view key) {
    auto hex = [](char c) -> int {
        if (c >= '0' && c <= '9') return c - '0';
        if (c >= 'a' && c <= 'f') return c - 'a' + 10;
        if (c >= 'A' && c <= 'F') return c - 'A' + 10;
        return -1;
    };
    std::string out;
    for (std::size_t i = 0; i < key.size(); ++i) {
        if (key[i] == '%' && i + 2 < key.size() &&
            hex(key[i + 1]) >= 0 && hex(key[i + 2]) >= 0) {
            out += static_cast<char>(hex(key[i + 1]) * 16 + hex(key[i + 2]));
            i += 2;
        } else out += key[i] == '+' ? ' ' : key[i];
    }
    return out;
}

// The core redactor handles plain query names. Also cover encoded names,
// userinfo and fragments, and fail closed for malformed provenance URLs.
std::string safe_url(const std::string& value, bool redact, const Redactor& redactor) {
    if (!redact || value.empty()) return value;
    try {
        auto url = parse_url(value);
        url.userinfo.clear();
        url.fragment.clear();
        url.has_fragment = false;
        std::string query;
        for (std::size_t start = 0; start < url.query.size();) {
            const auto end = url.query.find('&', start);
            const auto pair = url.query.substr(start, end == std::string::npos ? end : end - start);
            const auto eq = pair.find('=');
            const auto key = pair.substr(0, eq);
            if (!query.empty()) query += '&';
            query += redactor.is_sensitive_query_parameter(decode_key(key))
                ? key + "=" + redactor.policy().replacement : pair;
            if (end == std::string::npos) break;
            start = end + 1;
        }
        url.query = query;
        return url.to_string();
    } catch (...) { return redactor.policy().replacement; }
}

std::string method_name(std::string method) {
    for (char& c : method) if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    return method.empty() ? "GET" : method;
}

std::string request_url(const DiscoveredEndpoint& ep) {
    if (ep.request_content_type == "application/x-www-form-urlencoded") return ep.url;
    auto url = parse_url(ep.url);
    std::vector<std::string> names;
    for (std::size_t start = 0; start < url.query.size();) {
        const auto end = url.query.find('&', start);
        const auto pair = url.query.substr(start, end == std::string::npos ? end : end - start);
        names.push_back(decode_key(pair.substr(0, pair.find('='))));
        if (end == std::string::npos) break;
        start = end + 1;
    }
    constexpr char hex[] = "0123456789ABCDEF";
    for (const auto& param : ep.parameters) {
        if (std::find(names.begin(), names.end(), param) != names.end()) continue;
        names.push_back(param);
        if (!url.query.empty()) url.query += '&';
        for (unsigned char c : param) {
            if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
                (c >= '0' && c <= '9') || c == '-' || c == '_' || c == '.' || c == '~')
                url.query += static_cast<char>(c);
            else { url.query += '%'; url.query += hex[c >> 4]; url.query += hex[c & 15]; }
        }
        url.query += '=';
        url.has_query = true;
    }
    return url.to_string();
}

Scrape2PostmanResult convert(scrape2oapi::Scrape2OapiResult source,
                            const Scrape2PostmanOptions& options, const Redactor& redactor) {
    Scrape2PostmanResult result;
    result.resolved = std::move(source.resolved);
    result.endpoints = std::move(source.endpoints);
    result.warnings = std::move(source.warnings);
    result.assistant_browser = std::move(source.assistant_browser);
    result.postman_json = render_postman_json(result.resolved, options, redactor);
    return result;
}
